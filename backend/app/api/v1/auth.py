"""Accounts, sessions, devices, wake requests and the daily briefing."""

from __future__ import annotations

from typing import Annotated

from fastapi import APIRouter, Body, Response, status
from pydantic import BaseModel, Field

from app.api.deps import (
    AuthServiceDep,
    BriefingServiceDep,
    CurrentUserId,
)
from app.models.users import (
    Device,
    DevicePlatform,
    LoginRequest,
    RegisterRequest,
    TokenResponse,
    UserResponse,
)

router = APIRouter(tags=["auth"])


class RegisterDeviceRequest(BaseModel):
    device_id: str = Field(description="Stable id generated by the client")
    platform: DevicePlatform
    name: str = ""
    push_token: str | None = Field(
        default=None, description="Expo push token, if notifications are allowed"
    )


class DeviceResponse(BaseModel):
    id: str
    platform: DevicePlatform
    name: str
    has_push_token: bool

    @classmethod
    def from_domain(cls, device: Device) -> DeviceResponse:
        return cls(
            id=device.id,
            platform=device.platform,
            name=device.name,
            has_push_token=bool(device.push_token),
        )


class UpdatePreferencesRequest(BaseModel):
    tz: str | None = None
    display_name: str | None = None
    briefing_time: str | None = Field(default=None, description="HH:MM, local")
    briefing_enabled: bool | None = None


class WakeRequest(BaseModel):
    reason: str = Field(
        default="",
        max_length=200,
        description="Shown on the notification, e.g. 'Standup starting'",
    )
    source: str = Field(default="api", max_length=60)


class PushOutcome(BaseModel):
    sent: int
    failed: int
    detail: str = ""


# --- accounts -------------------------------------------------------------


@router.post(
    "/auth/register",
    response_model=UserResponse,
    status_code=status.HTTP_201_CREATED,
)
async def register(body: RegisterRequest, auth: AuthServiceDep) -> UserResponse:
    user = await auth.register(
        email=body.email,
        password=body.password,
        display_name=body.display_name,
        tz=body.tz,
    )
    return UserResponse.from_domain(user)


@router.post("/auth/login", response_model=TokenResponse)
async def login(body: LoginRequest, auth: AuthServiceDep) -> TokenResponse:
    return await auth.login(email=body.email, password=body.password)


@router.get("/auth/me", response_model=UserResponse)
async def me(user_id: CurrentUserId, auth: AuthServiceDep) -> UserResponse:
    return UserResponse.from_domain(await auth.get_user(user_id))


@router.patch("/auth/me", response_model=UserResponse)
async def update_me(
    body: UpdatePreferencesRequest,
    user_id: CurrentUserId,
    auth: AuthServiceDep,
) -> UserResponse:
    user = await auth.update_preferences(
        user_id,
        tz=body.tz,
        display_name=body.display_name,
        briefing_time=body.briefing_time,
        briefing_enabled=body.briefing_enabled,
    )
    return UserResponse.from_domain(user)


# --- devices --------------------------------------------------------------


@router.post(
    "/devices",
    response_model=DeviceResponse,
    summary="Register this device and its push token",
)
async def register_device(
    body: RegisterDeviceRequest,
    user_id: CurrentUserId,
    auth: AuthServiceDep,
) -> DeviceResponse:
    device = await auth.register_device(
        user_id=user_id,
        platform=body.platform,
        name=body.name,
        push_token=body.push_token,
        device_id=body.device_id,
    )
    return DeviceResponse.from_domain(device)


@router.get("/devices", response_model=list[DeviceResponse])
async def list_devices(
    user_id: CurrentUserId, auth: AuthServiceDep
) -> list[DeviceResponse]:
    devices = await auth.devices_for(user_id)
    return [DeviceResponse.from_domain(device) for device in devices]


@router.delete("/devices/{device_id}", status_code=status.HTTP_204_NO_CONTENT)
async def forget_device(
    device_id: str, user_id: CurrentUserId, auth: AuthServiceDep
) -> Response:
    await auth.forget_device(user_id, device_id)
    return Response(status_code=status.HTTP_204_NO_CONTENT)


# --- wake and briefing ----------------------------------------------------


@router.post(
    "/wake",
    response_model=PushOutcome,
    summary="Ask the user to start recording (does not start it)",
)
async def wake(
    user_id: CurrentUserId,
    auth: AuthServiceDep,
    briefing: BriefingServiceDep,
    body: Annotated[WakeRequest, Body()] = WakeRequest(),
) -> PushOutcome:
    """Sends an interrupting notification; recording still needs a tap.

    Starting the microphone from a remote trigger would be covert recording,
    which this product does not do. The notification is the wake-up call and
    the user's tap is the consent.
    """
    user = await auth.get_user(user_id)
    result = await briefing.send_wake_request(
        user, reason=body.reason, source=body.source
    )
    return PushOutcome(
        sent=result.sent,
        failed=result.failed,
        detail=(
            "No device registered for notifications."
            if not result.sent and not result.failed
            else "; ".join(result.errors[:2])
        ),
    )


@router.get(
    "/briefing",
    summary="Today's briefing, as the notification would say it",
)
async def get_briefing(
    user_id: CurrentUserId, auth: AuthServiceDep, briefing: BriefingServiceDep
) -> dict:
    user = await auth.get_user(user_id)
    built = await briefing.build(user)
    return {
        **built.model_dump(mode="json"),
        "headline": built.headline(),
        "body": built.body(),
        "is_empty": built.is_empty,
    }


@router.post(
    "/briefing/send",
    response_model=PushOutcome,
    summary="Send the briefing now (used for testing the schedule)",
)
async def send_briefing(
    user_id: CurrentUserId, auth: AuthServiceDep, briefing: BriefingServiceDep
) -> PushOutcome:
    user = await auth.get_user(user_id)
    result = await briefing.send_briefing(user)
    return PushOutcome(
        sent=result.sent,
        failed=result.failed,
        detail=(
            "No device registered for notifications."
            if not result.sent and not result.failed
            else "; ".join(result.errors[:2])
        ),
    )
